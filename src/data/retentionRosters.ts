/**
 * Returns eligible previous-season squad members for a specific franchise.
 * Strictly guarantees that no other franchise's players are returned.
 */
export function getPreviousSeasonSquadForTeam(teamId: string): PreviousSeasonPlayer[] {
  const normId = teamId?.toLowerCase().trim();
  return PREVIOUS_SEASON_SQUADS[normId] || [];
}

/**
 * Converts a PreviousSeasonPlayer to a standard Player object
 * with their official auction base price when entering the auction pool.
 */
export function convertToAuctionPlayer(p: PreviousSeasonPlayer): Player {
  return {
    id: p.id,
    name: p.name,
    role: p.role,
    nationality: p.nationality,
    isOverseas: p.isOverseas,
    battingStyle: p.battingStyle,
    bowlingStyle: p.bowlingStyle,
    age: p.age,
    basePriceCr: p.auctionBasePriceCr, // Must be official auction base price, never retention price!
    category: p.category,
    originalTeam: p.originalTeam,
    image: p.image || '',
    seasonStats: p.seasonStats,
    verifiedCutoff: '2026-01-15',
    isVerified2026: true
  };
}
